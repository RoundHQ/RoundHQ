create table if not exists public.staff_members (
  id bigint generated by default as identity primary key,
  auth_user_id uuid null,
  email text not null,
  full_name text not null,
  role text not null check (role in ('Admin', 'Staff', 'Operator')),
  is_active boolean not null default true,
  phone text null,
  notes text null,
  is_system_admin boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists staff_members_email_unique_idx
on public.staff_members (lower(email));

create unique index if not exists staff_members_auth_user_id_unique_idx
on public.staff_members (auth_user_id)
where auth_user_id is not null;

create unique index if not exists staff_members_single_system_admin_idx
on public.staff_members (is_system_admin)
where is_system_admin = true;

create table if not exists public.role_permissions (
  role text not null check (role in ('Admin', 'Staff', 'Operator')),
  page_key text not null check (
    page_key in (
      'dashboard',
      'schedule',
      'rounds',
      'history',
      'map',
      'actions',
      'commercial',
      'commercialDocs',
      'customers',
      'quotes',
      'invoices',
      'staff',
      'settings'
    )
  ),
  allowed boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (role, page_key)
);

